    # RODS  (creation + per-step redraw; the maths lives in class _Rod)
    # =========================================================================

    def _build_rods(self):
        """Create every agent's rod pieces once. They are only repositioned
        afterwards (resetBasePositionAndOrientation), never removed or
        recreated -- that is what keeps the rods steady on screen."""
        shapes = {}
        for units in ROD_PIECE_UNITS:
            verts, norms, idx = _tube_mesh(ROD_RADIUS_M, units * ROD_UNIT_M)
            shapes[units] = p.createVisualShape(
                p.GEOM_MESH, vertices=verts, indices=idx, normals=norms, rgbaColor=ROD_COLOR)
        for a in self.agents:
            a.rod = _Rod(shapes)

    def _sync_rods(self):
        """Redraw all four rods from the joint values. Called every physics
        step; each rod does nothing when it hasn't moved. Uses ONE batched
        getJointStates call (order = self._state_joints, see __init__)."""
        states = p.getJointStates(self.robot_id, self._state_joints)
        cx, cy = states[0][0], states[1][0]
        inward = {"front": states[2][0], "back": states[3][0]}
        for a, st in zip(self.agents, states[4:8]):        # the four hoists
            a.rod.sync(cx + a.dx,
                       cy + a.sign * (BOX_REACH_M - inward[a.side] + a.bay),
                       HOIST_ORIGIN_Z, rod_bottom_target(st[0]))

    def rod_intervals(self, agent):
        """The drawn rod's pieces as [(top_z, bottom_z)], see _Rod.intervals()."""
        return agent.rod.intervals()

