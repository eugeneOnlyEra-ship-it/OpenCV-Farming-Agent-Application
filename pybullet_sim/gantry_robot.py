    # COLLISION VOLUMES  (only verify_motion.py calls this; the simulation does not)
    # =========================================================================

    def robot_volumes(self):
        """Axis-aligned boxes for every physical part of the machine in its
        current pose, as (name, group, (min), (max), owner). group is 'wheel'
        (allowed to touch the rail), 'chassis' (fixed to the chassis) or
        'hoist' (moves with an agent); owner is 'chassis', a side ('front' /
        'back') for a drive box, or the agent's key. Used by verify_motion.py.

        WHY axis-aligned boxes: conservative (a box always contains the part) and
        cheap enough to test ~30 parts against ~500 obstacles every physics step.
        WHY here and not in the URDF: the URDF has no collision shapes.
        MAINTENANCE RULE: every physical part in urdf/gantry.urdf must be covered by a
        box below, with the same dimensions. Add a part to the URDF -> add a box here, or
        the clearance check silently stops protecting it.
        """
        cx, cy = self.chassis_xy()
        vols = []

        def box(name, group, owner, x, y, z, hx, hy, hz):
            """Record one part: centre (x, y, z) and half-sizes (hx, hy, hz) -> an (min, max) AABB."""
            vols.append((name, group, (x - hx, y - hy, z - hz), (x + hx, y + hy, z + hz), owner))

        # ---- chassis: plate, four wheels (group "wheel": the only parts allowed to touch the rail),
        #      two portal posts and two outrigger rails -------------------------------------
        wheel_z = BASE_Z - 0.038
        box("chassis plate", "chassis", "chassis", cx, cy, BASE_Z, 0.13, 0.10, 0.015)
        box("wheel +x", "wheel", "chassis", cx + 0.05, cy, wheel_z, 0.022, 0.012, 0.022)
        box("wheel -x", "wheel", "chassis", cx - 0.05, cy, wheel_z, 0.022, 0.012, 0.022)
        box("wheel +y", "wheel", "chassis", cx, cy + 0.05, wheel_z, 0.012, 0.022, 0.022)
        box("wheel -y", "wheel", "chassis", cx, cy - 0.05, wheel_z, 0.012, 0.022, 0.022)
        for sx in (1, -1):
            box(f"portal post {'+' if sx > 0 else '-'}x", "chassis", "chassis",
                cx + sx * AGENT_X_OFFSET_M, cy, BASE_Z + 0.115, 0.012, 0.03, 0.10)
            box(f"outrigger {'+' if sx > 0 else '-'}x", "chassis", "chassis",
                cx + sx * AGENT_X_OFFSET_M, cy, BASE_Z + 0.227, 0.02, 0.55, 0.012)

        # ---- the two drive boxes (they MOVE: their y depends on how far each has slid in) ----
        # one merged drive box per side: body + common lid + both gear-motors +
        # encoder caps, as one box from the hoist origin (its bottom face) up
        for side, sign in (("front", 1), ("back", -1)):
            by = cy + sign * (BOX_REACH_M - self.box_inward(side))
            box(f"{side} drive box", "chassis", side, cx, by,
                HOIST_ORIGIN_Z + BOX_TOP_ABOVE_ORIGIN_M / 2,
                BOX_HALF_X_M, BOX_HALF_Y_M, BOX_TOP_ABOVE_ORIGIN_M / 2)

        # ---- per agent: rod, stub, yoke, sleeve, bars, carriage, head (+ applicator) ---------
        # Everything down to the yoke hangs from the rod (x fixed, z follows the hoist); the
        # carriage, head and applicator additionally slide along x by the traverse offset `st`.
        for a in self.agents:
            hx = cx + a.dx                                   # the rod's x (fixed)
            hy = cy + self.rod_y(a)                          # the rod's y
            h = self._joint(a.joint)
            st = self.stage_offset(a)
            zh = HOIST_ORIGIN_Z - h                          # the hoist link's origin
            tool_z = zh - HEAD_DROP_M
            # the rod, its stub + yoke, the horizontal guide rail (fixed to the rod's bottom)
            rod_len = rod_units_for(HOIST_ORIGIN_Z, rod_bottom_target(h)) * ROD_UNIT_M
            box(f"{a.key} rod", "hoist", a.key, hx, hy, HOIST_ORIGIN_Z - rod_len / 2,
                ROD_RADIUS_M, ROD_RADIUS_M, rod_len / 2)
            box(f"{a.key} stub", "hoist", a.key, hx, hy, zh - 0.015, 0.02, 0.02, 0.015)
            box(f"{a.key} yoke", "hoist", a.key, hx, hy, zh - 0.036, 0.025, 0.02, 0.006)
            # the telescoping traverse: a fixed sleeve behind the rod, two bars sliding out of it
            behind = hx - a.bar_dir * BAR_CENTRE_BEHIND_M
            box(f"{a.key} sleeve", "hoist", a.key, behind, hy, zh - RAIL_DROP_M, BAR_HALF_LENGTH_M, 0.015, 0.013)
            s1 = self._joint(a.stage_joints[0])
            c1, c2 = behind + s1, behind + st                # bar 1 and bar 2 centres
            lo_x, hi_x = min(c1, c2) - BAR_HALF_LENGTH_M, max(c1, c2) + BAR_HALF_LENGTH_M
            box(f"{a.key} bars", "hoist", a.key, (lo_x + hi_x) / 2, hy, zh - RAIL_DROP_M,
                (hi_x - lo_x) / 2, 0.011, 0.010)
            # the carriage and the tool hanging from it: these slide along X with the stage
            box(f"{a.key} carriage", "hoist", a.key, hx + st, hy, zh - RAIL_DROP_M, *CARRIAGE_HALF_M)
            if a.role == "camera":
                box(f"{a.key} head", "hoist", a.key, hx + st, hy, tool_z,
                    CAMERA_HALF_X_M, CAMERA_HALF_Y_M, HEAD_HALF_HEIGHT_M)
            else:
                # tank + nozzle tube as one box: from the tank's far side to the tube's end
                far = SERVICE_TANK_RADIUS_M
                near = SERVICE_NOZZLE_TUBE_END_M
                box(f"{a.key} head", "hoist", a.key, hx + st, hy + a.toward * (near - far) / 2, tool_z,
                    SERVICE_TANK_RADIUS_M, (near + far) / 2, HEAD_HALF_HEIGHT_M)
                # the contact applicator (rod + pad), wherever it is slid out to
                e = self.applicator_extension(a)
                back = SERVICE_NOZZLE_TUBE_END_M + e - APPLICATOR_ROD_BACK_M
                front = SERVICE_NOZZLE_TUBE_END_M + e + APPLICATOR_PAD_FRONT_M
                box(f"{a.key} applicator", "hoist", a.key, hx + st, hy + a.toward * (front + back) / 2, tool_z,
                    APPLICATOR_PAD_RADIUS_M, (front - back) / 2, APPLICATOR_PAD_RADIUS_M)
        return vols

    # =========================================================================
    # THE SCHEDULER  (cooperative multitasking, no threads)
    # =========================================================================
    # Everything that takes time is a GENERATOR that `yield`s once per physics step:
    #
    #     def _g_something(self):
    #         yield from self._g_settle({joint: target})   # "move this joint, resume when arrived"
    #         yield from self._g_wait(0.5)                  # "do nothing for 0.5 s of sim time"
    #         yield from self._g_wait_until(lambda: flag)   # "block until another task sets flag"
    #
    # _run(tasks) advances every live generator by ONE yield, steps the simulation once, and
    # repeats until all have finished. So the four agents genuinely act at the same time, and
    # one agent can wait for another (the service agent waits for the camera) with an ordinary
    # loop -- no locks, no threads. Blocking helpers (_settle, dwell) just run a single generator.
    #
    # Rule of thumb when adding behaviour: express it as a generator built from these three
    # primitives, and give it to _run() alongside the others.

    def _step(self, step_sleep=0.0):
        """Advance the world by one physics step (1/240 s) and do the per-step
        chores: redraw the rods, optionally sleep (for a watchable GUI), and call
        the on_step hook (verify_motion.py's checker runs here)."""
        p.stepSimulation()
        self.sim_steps += 1
        self._sync_rods()
        self._sync_grippers()
        if step_sleep:
            time.sleep(step_sleep)
        if self.on_step is not None:
            self.on_step()

    def _run(self, tasks, step_sleep=0.0):
        """Run generators to completion in lock-step with the simulation.
        Each loop: give every live task one turn (next(t) runs it up to its next
        `yield`), then step the physics once. A task that returns is dropped.
        Returns physics steps taken. MAX_RUN_STEPS turns a deadlock (two tasks
        waiting on each other) into an error instead of an infinite loop."""
        tasks = list(tasks)
        steps = 0
        while tasks:
            for t in list(tasks):
                try:
                    next(t)
                except StopIteration:
                    tasks.remove(t)
            if not tasks:
                break
            self._step(step_sleep)
            steps += 1
            if steps > MAX_RUN_STEPS:
                raise RuntimeError("scheduler ran too long -- an agent is probably waiting on something that never happens")
        return steps

    def _g_settle(self, targets):
        """Command each {joint: target} and yield until every one has arrived
        and stopped (or the step cap is hit, so a bad target can't hang).

        "Arrived" = |position - target| < that joint's tolerance AND |velocity| <
        VELOCITY_TOLERANCE, checked AFTER each step (hence yield-then-check).
        Note joints settle ~1 mm SHORT of a target, which is why tolerances are 4 mm
        for the fine axes and why touching a plant is aimed 1 mm short."""
        for joint, target in targets.items():
            force, vel = self._drive[joint]
            p.setJointMotorControl2(
                self.robot_id, joint, p.POSITION_CONTROL,
                targetPosition=target, force=force, maxVelocity=vel * self.speed_scale,
            )
        steps = 0
        while steps < MAX_SETTLE_STEPS:
            yield
            steps += 1
            arrived = True
            for joint, target in targets.items():
                pos, vel = p.getJointState(self.robot_id, joint)[:2]
                tol = self._tol.get(joint, POSITION_TOLERANCE)
                if abs(pos - target) >= tol or abs(vel) >= VELOCITY_TOLERANCE:
                    arrived = False
                    break
            if arrived:
                return

