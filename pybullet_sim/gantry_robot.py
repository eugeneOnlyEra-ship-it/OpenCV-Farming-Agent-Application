"""
gantry_robot.py  --  the machine, its four agents, and the scheduler that works them
=====================================================================================

WHAT THIS FILE IS
    A PyBullet model of ONE rail-riding machine that services a farm of vertical
    "pole" stations, plus everything needed to drive it: the scene (poles, rails,
    trough pods, plants), the motion primitives, a tiny cooperative scheduler,
    the rail router and the camera/service work-flow. main.py drives it;
    verify_motion.py audits it. The physical machine itself is described twice
    and the two must agree:
        * urdf/gantry.urdf            joints + visuals (GENERATED by
                                      tools/generate_gantry_urdf.py, which IMPORTS
                                      the shared dimensions from THIS file)
        * the constants below         used for planning, for placing the drawn rods,
                                      and for the collision volumes in robot_volumes()

HOW TO READ THIS FILE (top to bottom)
     1. CONSTANTS, in six labelled groups (1 motion, 2 farm structure, 3 machine
        geometry + agent placement, 4 tool heads, 5 rod drawing, 6 the job).
     2. Small pure helpers: _tube_mesh, hoist_extension_for, rod_bottom_target,
        rod_units_for, station_position.
     3. class _Rod   -- draws one agent's telescoping rod from fixed tube pieces.
     4. class Agent  -- plain data: which side/role, where it hangs, its joints.
     5. class GantryRobot
          construction        __init__ -> _build_farm_structure, _add_plants,
                              _build_rods, _park_initial_pose
          state readers       chassis_xy, box_inward, stage_offset, all_stowed,
                              agent_head_position, applicator_tip, ...
          collision volumes   robot_volumes()  (for verify_motion.py only)
          scheduler           _step, _run, _g_settle, _g_wait, _g_wait_until
          routing + motion    _plan_rail_route, _drive_to, _stow_all,
                              disengage_boxes, engage_boxes
          the two jobs        _g_camera, _g_service
          PUBLIC API          go_to_station, service_station, park_at_dock,
                              dwell, mark_pod_decision, disconnect

VOCABULARY AND COORDINATES  (metres, world frame, z up)
     x       along a row, left -> right (column 0 is x = 0).
     y       across rows. Row r's beam is at y = r * ROW_SPACING_M (1.32 m).
             "front" = the +Y side of a beam, "back" = the -Y side.
     pole / station   one vertical pole (row r, column c); it carries 4 layers of
                      trough pods on each side = 8 pods.  The machine stops with
                      its centre exactly over the pole (x = c*0.75, y = r*1.32).
     pod / trough     an elongated box (0.44 m long along x) sticking out of a pole;
                      its aisle-facing wall is the "face" (0.24 m from the pole's axis).
     plant            PLANTS_PER_POD (3) plants growing vertically from the
                      TOP of each trough, at x = pole_x + PLANT_X_OFFSETS_M.
     rail             the overhead lattice the machine rides ON. Horizontal rails:
                      1 (top dock), 2, 3, 4 (the three rows), "end" (bottom dock).
                      Vertical rails: only the two OUTER ones, at x = 0 and x = 1.5.
     agent            one hoist (a vertical rod that lengthens) + a traverse head.
                      Four: {front, back} x {camera, service}.
     head             what hangs at the bottom of the rod: a camera or a service tank,
                      on a 2-stage telescoping traverse that slides it along x.
     stowed           hoist fully up, applicator in, head centred on its traverse.
     home / centred   head at offset 0 from its rod.
     engaged          drive boxes slid OUT to their operating position (0.445 m
                      either side of the beam);  disengaged = slid IN (0.26 m).

THE RAIL NETWORK AND THE ROUTE (matches the numbered sketch)
                 1  ============================   <- top dock bar  (start, parked)
                    ||                          ||
                 2  o=====o=====o    row 0        o = a pole/station
                    ||                          ||   || = the two outer vertical rails
                 3  o=====o=====o    row 1
                    ||                          ||
                 4  o=====o=====o    row 2
                    ||                          ||
               end  ============================   <- bottom dock bar (finish)
     Rails 2 -> 3 -> 4 are worked left->right, right->left, left->right (a serpentine),
     so moving to the next row is always "down the nearest outer rail". The machine
     never cuts diagonally through open air: X on a horizontal rail, or Y on an
     outer vertical rail, one axis at a time.

THE FOUR AGENTS  (plan view of one station; numbers are metres from the beam)
                          FRONT side (+Y)
        camera  x-0.11, 0.505 out        service  x+0.11, 0.385 out     <- staggered depth
     ---------------------------- beam / pole ---------------------------
        camera  x-0.11, 0.505 out        service  x+0.11, 0.385 out
                          BACK side (-Y)
     The two agents on a side share ONE drive box. The camera bay hangs 0.06 m
     further out than the box centre and the service bay 0.06 m further in: that
     stagger is what lets each head slide along the whole pod past the OTHER
     agent's rod. At the two outer poles the machine sits over the outer vertical
     rail and the two agents straddle it (0.11 m each side).

HOW A STATION IS WORKED  (service_station)
     Front and back faces run at the same time. On each face two generators
     (_g_camera, _g_service) run as a two-stage pipeline, top layer down:
       camera   for each pod: slide the head along it imaging each plant ->
                assess(pod) callback (classify + decide) -> hold -> move to the
                next pod's height ("camera_left") -> ...
       service  for each pod: WAIT until the camera has assessed it AND left it,
                then, if the decision needs service: go to the pod's height and
                work plant by plant (head in front of the plant, applicator out
                until the pad touches it, hold, applicator in, next plant).
     When both faces are done and everything is stowed, the machine moves on:
     straight along the beam to the next station on the same pole, or -- for a
     different pole or a dock -- first slides the drive boxes in, drives down an
     outer rail, and slides them out again on arrival.

SAFETY INVARIANTS  (enforced here by assert/ordering, AND re-checked every physics
step by verify_motion.py -- if you add a motion, keep these true)
     * The chassis moves along ONE axis at a time, only along a rail.
     * The chassis only moves with every hoist stowed, every head centred and
       every applicator in  (all_stowed()).
     * The chassis moves in Y (changes pole) only with the drive boxes slid in.
     * A drive box only slides with everything stowed and the machine still.
     * Hoists only deploy with the drive boxes engaged.
     * A head only slides along the pod with its applicator in; the applicator
       only slides out while the hoist and the head are standing still.
     * The service agent only starts on a pod after the camera has assessed it
       and moved on.

EVENT LOG  (self.events; also delivered live to on_event(dict))
     Every dict has "step" (sim step), "kind", "pod_id" (or None), "agent" (or None).
       station_start / station_done   + row, col
       boxes_disengage / boxes_engage
       plant_scan        + plant        camera head stopped in front of a plant
       assess            camera is in position; the assess() callback is called next
       camera_left                      camera finished the pod and moved on
       service_skip                     no service needed for this pod
       service_start     + action       service agent arrived at the pod
       service_contact   + action, plant  pad touching a plant
       service_done      + action       all plants on the pod done, tag placed
     main.py prints/logs from these; verify_motion.py audits them.

PUBLIC API (what other files call)
     GantryRobot(pods, gui=True, show_trail=True, speed_scale=1.0)
     .park_at_dock(dock_y)          stow, disengage, drive to a dock bar
     .service_station(station, assess)   drive to a pole and work it (see above)
     .go_to_station(row, col)       just the driving part of service_station
     .mark_pod_decision(pod_id, action)  recolour a trough green/yellow/red
     .dwell(seconds), .disconnect()
     .events, .on_event, .on_step   observation hooks (verify_motion.py uses them)
     .obstacles, .robot_volumes()   geometry for the clearance checker

CHANGING THINGS
     See docs/EXTENDING.md for step-by-step recipes (new service action, more plants,
     new agent, new rule, ...). After ANY change:  python3 run_checks.py
"""

