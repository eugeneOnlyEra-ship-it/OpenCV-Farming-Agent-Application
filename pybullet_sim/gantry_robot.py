def _tube_mesh(radius, length, segments=ROD_TUBE_SEGMENTS):
    """Open tube along Z (no end caps) with smooth radial normals, as
    (vertices, indices, normals). Stacked end to end it shades exactly like
    one continuous cylinder; the ends are hidden inside the hoist stub at the
    top and the yoke at the bottom.

    Why a custom mesh instead of p.GEOM_CYLINDER: PyBullet's built-in cylinder
    shades its two ends differently from its middle, so a stack of them looks
    like beads on a string. Here every vertex normal points radially outward
    (c, s, 0), so all pieces shade identically wherever they are joined.
    """
    verts, norms, idx = [], [], []
    h = length / 2
    for i in range(segments):
        a = 2 * math.pi * i / segments
        c, s = math.cos(a), math.sin(a)
        verts += [[radius * c, radius * s, -h], [radius * c, radius * s, h]]
        norms += [[c, s, 0.0], [c, s, 0.0]]
    for i in range(segments):
        j = (i + 1) % segments
        b0, t0, b1, t1 = 2 * i, 2 * i + 1, 2 * j, 2 * j + 1
        idx += [b0, b1, t1, b0, t1, t0]
    return verts, norms, idx


def hoist_extension_for(z):
    """Hoist joint value that puts the tool head's centre at world height z.

    The hoist joint measures how far the hoist link has moved DOWN from
    HOIST_ORIGIN_Z, and the head hangs HEAD_DROP_M below that link. E.g. for
    the lowest pod (z = 0.28): 2.535 - 0.095 - 0.28 = 2.16 m of extension (the
    joint limit is 2.6 m). Used for every "go to this pod" move."""
    return HOIST_ORIGIN_Z - HEAD_DROP_M - z


def rod_bottom_target(hoist):
    """World height the drawn rod's bottom end should reach for a hoist
    extension `hoist`: ROD_YOKE_INSET_M below the hoist link's origin, i.e.
    inside the yoke block, so the rod visibly plugs into the traverse."""
    return HOIST_ORIGIN_Z - hoist - ROD_YOKE_INSET_M


def rod_units_for(top_z, bottom_z):
    """How many ROD_UNIT_M (5 mm) units the drawn rod spans for a gap from
    `top_z` (the bottom face of the drive box) down to `bottom_z`.

    Rounded UP so the rod never stops short of the yoke (the extra <= 5 mm is
    hidden inside it), clamped to [ROD_MIN_UNITS, ROD_MAX_UNITS]. The number is
    then decomposed into binary pieces by _Rod.sync()."""
    n = max(ROD_MIN_UNITS, math.ceil((top_z - bottom_z) / ROD_UNIT_M - 1e-9))
    return min(n, ROD_MAX_UNITS)


def station_position(row, col):
    """(x, y) where the machine stops to work station (row, col): its centre
    exactly over the pole. This is also a point ON the rail lattice, which the
    router relies on (both ends of a route must be on a horizontal rail)."""
    return col * COLUMN_SPACING_M, row * ROW_SPACING_M


# =============================================================================
# THE ROD  (a lengthening vertical pole, drawn as a stack of fixed tube pieces)
# =============================================================================
class _Rod:
    """The persistent tube pieces that draw ONE agent's rod.

    THE PROBLEM: the rod must be as long as the gap between the drive box and the
    head (0.4 - 2.2 m, changing every step). PyBullet cannot resize a body, and
    deleting + recreating one body per step made the rod flicker in the GUI.

    THE SOLUTION: create nine tube bodies ONCE, of lengths 5 mm x (256, 128, 64, 32,
    16, 8, 4, 2, 1), park them out of sight, and for each new length show exactly
    the pieces whose bits are set in (length / 5 mm), stacked end to end from the
    box downward. Changing length only MOVES existing bodies
    (resetBasePositionAndOrientation): no creation, no deletion, no flicker.

    self.pieces  [(units, body_id)] largest piece first
    self.pose    per piece: the (x, y, z) it is currently shown at, or None if parked
    self.last_key  cache key: nothing is touched unless the rod really moved
    """

    def __init__(self, shapes):
        """`shapes` maps each piece length (in units) to a shared visual shape id;
        creates the nine bodies parked out of sight (see the class docstring)."""
        self.pieces = []       # [(units, body_id)]
        self.pose = []         # per piece: (x, y, z) it is shown at, or None if parked
        self.last_key = None
        for units in ROD_PIECE_UNITS:
            body = p.createMultiBody(
                baseMass=0, baseCollisionShapeIndex=-1, baseVisualShapeIndex=shapes[units],
                basePosition=[0, 0, ROD_PARK_Z],
            )
            self.pieces.append((units, body))
            self.pose.append(None)

    def sync(self, x, y, top_z, bottom_z):
        """Stack the pieces from `top_z` down into the yoke at `bottom_z`.
        Moves only existing bodies, and only the ones whose position changed.
        (x, y) is where the rod hangs; called every physics step, so the early
        return on an unchanged key is what keeps it cheap."""
        n_units = rod_units_for(top_z, bottom_z)
        key = (n_units, round(x, 4), round(y, 4), round(top_z, 4))
        if key == self.last_key:
            return
        self.last_key = key

        # Walk the pieces largest-first; a piece is shown iff its bit is set in n_units. z is
        # the running bottom edge of the stack, so pieces sit end to end going DOWN.
        x, y = round(x, 5), round(y, 5)
        z = top_z
        for idx, (units, body) in enumerate(self.pieces):
            if n_units & units:
                length = units * ROD_UNIT_M
                pose = (x, y, round(z - length / 2, 5))
                z -= length
            else:
                pose = None
            if pose != self.pose[idx]:
                p.resetBasePositionAndOrientation(
                    body, pose if pose is not None else [0, 0, ROD_PARK_Z], [0, 0, 0, 1])
                self.pose[idx] = pose

    def intervals(self):
        """[(top_z, bottom_z), ...] of every piece currently shown, read back
        from the ACTUAL PyBullet bodies (not from our own bookkeeping), highest
        first. verify_motion.py uses it to prove the drawn rod is one unbroken
        column from the drive box to the yoke at every step."""
        spans = []
        for (units, body), pose in zip(self.pieces, self.pose):
            if pose is None:
                continue
            z = p.getBasePositionAndOrientation(body)[0][2]
            half = units * ROD_UNIT_M / 2
            spans.append((z + half, z - half))
        return sorted(spans, reverse=True)


# =============================================================================
# AGENT  (plain data: which of the four it is, where it hangs, which joints are its)
# =============================================================================
class Agent:
    """One hoist + traverse + tool. side: 'front' (+Y) or 'back' (-Y); role:
    'camera' or 'service'. Created four times by GantryRobot.__init__.

    Fixed by side/role (set here):
      key        "front_camera" ... -- the name used in events, joints and logs
      dx         rod's x offset from the machine centre (-0.11 camera / +0.11 service)
      sign       +1 front / -1 back: the agent hangs at chassis_y + sign * lateral
      toward     Y direction FROM the agent TOWARD the pods it works (-1 front, +1 back)
      bay        +0.06 camera (further out) / -0.06 service (further in), see BAY_OFFSET_M
      bar_dir    the traverse extends toward +x (camera) or -x (service)
    Filled in by GantryRobot.__init__ from the URDF's joint names:
      joint            hoist joint index (rod up/down)
      stage_joints     (stage1, stage2) joint indices: the telescoping traverse
      applicator_joint applicator joint index (service agents only, else None)
      rod              its _Rod (the drawn pole)
    """

    def __init__(self, side, role):
        """Derive everything that follows from side/role (see the class docstring);
        joints and the rod are attached later by GantryRobot.__init__."""
        self.side = side
        self.role = role
        self.key = f"{side}_{role}"
        self.dx = -AGENT_X_OFFSET_M if role == "camera" else AGENT_X_OFFSET_M
        # +1 for the front (+Y) side of the beam, -1 for the back (-Y) side; the
        # agent hangs at  chassis_y + sign * (BOX_REACH_M - box_inward_travel + bay)
        self.sign = 1 if side == "front" else -1
        # sign of the Y direction from this agent toward the pods it works on
        self.toward = -1 if side == "front" else 1
        # camera rods hang BAY_OFFSET_M further out than the box centre, service rods further in
        self.bay = BAY_OFFSET_M if role == "camera" else -BAY_OFFSET_M
        self.joint = None
        self.stage_joints = None         # (stage1, stage2): the telescoping traverse (all four agents)
        # the traverse extends toward +x for camera agents, -x for service agents
        self.bar_dir = 1 if role == "camera" else -1
        self.applicator_joint = None     # service agents only
        self.rod = None


AGENT_ORDER = (("front", "camera"), ("front", "service"), ("back", "camera"), ("back", "service"))


# =============================================================================
# THE ROBOT
# =============================================================================
class GantryRobot:
    """The whole simulation: PyBullet world + the machine + its scheduler.

    One instance owns one PyBullet connection. Typical use (see main.py):
        robot = GantryRobot(pods=service_visit_order(), gui=False)
        robot.on_event = my_callback            # optional
        robot.park_at_dock(TOP_DOCK_Y)
        for station in group_by_station(pods):
            robot.service_station(station, assess)   # assess(pod) -> {"service_action": ...}
        robot.park_at_dock(BOTTOM_DOCK_Y)
        robot.disconnect()

    Public attributes worth knowing: agents (the four Agent objects), events (the
    event log), obstacles (static geometry for the clearance checker),
    service_markers (tags placed so far), sim_steps.
    """

    def __init__(self, pods, gui=True, show_trail=True, speed_scale=1.0):
        """Connect to PyBullet, build the farm, load the URDF, park on dock 1.

        pods         the FULL list of pod dicts (pod_registry.service_visit_order());
                     used to draw every trough/plant even on a partial run
        gui          True = PyBullet GUI window, False = headless (p.DIRECT)
        show_trail   draw a red line along the path the chassis has driven (GUI only)
        speed_scale  multiplies every joint's max velocity (1.0 = tuned speed)
        """
        self.pods = pods
        self.gui = gui
        self.show_trail = show_trail and gui
        # multiplies every joint's max velocity (1.0 = the 0.6 m/s the
        # design was tuned at). Higher = faster animation, fewer sim steps.
        self.speed_scale = speed_scale
        # --- bookkeeping shared with main.py / verify_motion.py -------------------------------
        self.pod_marker_ids = {}
        # Each plant is its own removable/replantable PyBullet visual body.
        self.plant_body_ids = {}       # pod_id -> {plant_index: body_id | None}
        self.plant_specs = {}          # (pod_id, plant_index) -> geometry recipe
        self.active_grippers = {}      # service agent key -> animated visual gripper state
        self.service_markers = {}      # pod_id -> body id of the "serviced" tag
        self.service_marker_bounds = {}  # pod_id -> (min, max) AABB, for verify_motion.py
        # Multi-view localization results are keyed by pod ID. Callback is optional
        # so the simulator can be used by both the GUI and headless checks.
        self.localization_records = {}
        self.on_localization = None
        self.rig = None                # calibrated two-camera head rig (stereo_rig), None = single camera
        self._rig_checked = False
        # Every trough carries a printed tag; the camera agent reads it to learn WHICH pod it is looking at.
        self.pod_label_ids = {}        # pod_id -> body id of that trough's tag plate
        self.pod_identities = {}       # pod_id -> the camera agent's latest tag-read result for that pod
        self.reads_pod_tags = True     # lets the bridge know identity comes from vision, not from the dispatch list
        self.label_reader = default_reader()
        self._label_dir = None
        # every static thing the machine must stay clear of, recorded as it is
        # built: (name, (xmin,ymin,zmin), (xmax,ymax,zmax)). Used by
        # verify_motion.py; cylinders are recorded as their bounding box.
        self.obstacles = []
        # optional callbacks: on_step() after EVERY physics step; on_event(dict)
        # for the camera/service hand-offs (see _emit)
        self.on_step = None
        self.on_event = None
        self.events = []
        self.sim_steps = 0
        self.current_service = {}      # agent key -> pod_id while its applicator is out on that pod
        self.current_plant = {}        # agent key -> plant index it is touching then

        # --- 1. the PyBullet world (240 Hz, gravity on, real-time OFF: WE decide when time passes) ---
        connection_mode = p.GUI if gui else p.DIRECT
        self.client = p.connect(connection_mode)
        p.setAdditionalSearchPath(pybullet_data.getDataPath())
        p.setGravity(0, 0, -9.8)
        p.setRealTimeSimulation(0)
        p.setTimeStep(1.0 / 240.0)

        # a checkered floor purely for the eye; nothing collides with it
        p.loadURDF("plane.urdf")

        # --- 2. the machine. The URDF is GENERATED by tools/generate_gantry_urdf.py. ---
        urdf_path = os.path.join(os.path.dirname(__file__), "urdf", "gantry.urdf")
        # The URDF's base sits at world (0, 0, chassis height): carriage_joint
        # and row_joint values are therefore plain world X / Y coordinates.
        self.robot_id = p.loadURDF(
            urdf_path, basePosition=[0, 0, BASE_Z], useFixedBase=True
        )

        # --- 3. map joint NAMES -> indices. We always look joints up by name, never by number, so
        #        re-generating the URDF with joints added/reordered cannot silently break us. ---
        names = {p.getJointInfo(self.robot_id, i)[1].decode(): i
                 for i in range(p.getNumJoints(self.robot_id))}
        self.carriage_joint = names["carriage_joint"]
        self.row_joint = names["row_joint"]
        self.box_joint = {side: names[f"box_{side}"] for side in ("front", "back")}
        self.agents = []
        for side, role in AGENT_ORDER:
            a = Agent(side, role)
            a.joint = names[f"hoist_{a.key}"]
            a.stage_joints = (names[f"stage1_{a.key}"], names[f"stage2_{a.key}"])
            if role == "service":
                a.applicator_joint = names[f"applicator_{a.key}"]
            self.current_service[a.key] = None
            self.current_plant[a.key] = None
            self.agents.append(a)
        # --- 4. per-joint control tables: (force, max velocity) and, where tighter than the
        #        default, a per-joint arrival tolerance. Read by _g_settle. ---
        self._agent = {(a.side, a.role): a for a in self.agents}
        self._drive = {self.carriage_joint: JOINT_FORCE_VEL["carriage"],
                       self.row_joint: JOINT_FORCE_VEL["row"]}
        self._tol = {}
        for j in self.box_joint.values():
            self._drive[j] = JOINT_FORCE_VEL["box"]
            self._tol[j] = BOX_TOLERANCE_M
        for a in self.agents:
            self._drive[a.joint] = JOINT_FORCE_VEL["hoist"]
            for j in a.stage_joints:
                self._drive[j] = JOINT_FORCE_VEL["stage"]
                self._tol[j] = STAGE_TOLERANCE_M
            if a.applicator_joint is not None:
                self._drive[a.applicator_joint] = JOINT_FORCE_VEL["applicator"]
                self._tol[a.applicator_joint] = APPLICATOR_TOLERANCE_M
        # Joint order used by _sync_rods() to read everything in ONE getJointStates call. THE
        # ORDER IS A CONTRACT: [0]=carriage(x) [1]=row(y) [2]=front box [3]=back box,
        # [4:8]=the four hoists (in AGENT_ORDER), [8:12]=stage1 x4, [12:16]=stage2 x4.
        self._state_joints = ([self.carriage_joint, self.row_joint,
                               self.box_joint["front"], self.box_joint["back"]]
                              + [a.joint for a in self.agents]
                              + [a.stage_joints[0] for a in self.agents]
                              + [a.stage_joints[1] for a in self.agents])

        # --- 5. build the scene, the drawn rods, and park on dock 1 (boxes slid in, all stowed) ---
        self._build_farm_structure()
        self._build_rods()
        self._park_initial_pose()
        self._sync_rods()

        # --- 6. GUI only: rail number labels and a default camera view of the whole farm ---
        if gui:
            self._add_rail_labels()
            farm_span_x = RAIL_X_MAX - RAIL_X_MIN
            farm_span_y = BOTTOM_DOCK_Y - TOP_DOCK_Y
            p.resetDebugVisualizerCamera(
                cameraDistance=max(3.2, farm_span_y * 1.05), cameraYaw=35, cameraPitch=-38,
                cameraTargetPosition=[farm_span_x / 2, (TOP_DOCK_Y + BOTTOM_DOCK_Y) / 2,
                                      TOP_TROUGH_Z / 2],
            )

    def agent(self, side, role):
        """The Agent for ('front'|'back', 'camera'|'service')."""
        return self._agent[(side, role)]

    # =========================================================================
    # SCENE CONSTRUCTION  (poles, rails, troughs, plants, tags) -- all visual-only
    # =========================================================================
    # Nothing in the scene has a collision shape. The machine is kept clear of it by its
    # routing, and verify_motion.py checks the clearances numerically from self.obstacles
    # (every static thing is recorded there as a name + axis-aligned bounding box as it is
    # built). To add a new static object the machine must avoid: create it, then append
    # (name, (xmin,ymin,zmin), (xmax,ymax,zmax)) to self.obstacles.

    def _build_farm_structure(self):
        """Poles, the rail network from the sketch, and every trough.
        All visual-only (no collision shapes): the machine is kept clear of
        all of it by its routing, and verify_motion.py checks that
        numerically -- letting the physics engine push it around would just
        make it look like it is fighting the structure."""
        pole_grey = (0.42, 0.42, 0.45, 1.0)
        rail_grey = (0.5, 0.5, 0.53, 1.0)
        dock_brown = (0.55, 0.42, 0.2, 1.0)

        # poles: end flush with the rail's top face so the wheels roll straight over them
        for row in range(ROWS):
            row_y = row * ROW_SPACING_M
            for col in range(COLUMNS):
                station_x = col * COLUMN_SPACING_M
                self._add_static_cylinder(
                    name=f"pole R{row}C{col}", radius=POLE_RADIUS_M, height=POLE_TOP_Z,
                    position=[station_x, row_y, POLE_TOP_Z / 2], color=pole_grey,
                )

        # horizontal rails = the numbered "horizontal poles": 1, 2, 3, 4, end
        half_len = (RAIL_X_MAX - RAIL_X_MIN) / 2 + BEAM_HALF_THICKNESS_M  # close the corners
        for label, y in HORIZONTAL_RAILS:
            is_dock = label in ("1", "end")
            self._add_static_box(
                name=f"rail {label}",
                half_extents=[half_len, BEAM_HALF_THICKNESS_M, BEAM_HALF_THICKNESS_M],
                position=[(RAIL_X_MIN + RAIL_X_MAX) / 2, y, TOP_RAIL_HEIGHT_M],
                color=dock_brown if is_dock else rail_grey,
            )

        # the two outer vertical rails, dock bar to dock bar. Brown where
        # they run out to a dock, grey between the first and last row.
        first_row_y = 0.0
        last_row_y = (ROWS - 1) * ROW_SPACING_M
        segments = [
            (TOP_DOCK_Y - BEAM_HALF_THICKNESS_M, first_row_y, dock_brown),
            (first_row_y, last_row_y, rail_grey),
            (last_row_y, BOTTOM_DOCK_Y + BEAM_HALF_THICKNESS_M, dock_brown),
        ]
        for x in VERTICAL_RAIL_XS:
            for y0, y1, color in segments:
                self._add_static_box(
                    name=f"vertical rail x={x:g}",
                    half_extents=[BEAM_HALF_THICKNESS_M, (y1 - y0) / 2, BEAM_HALF_THICKNESS_M],
                    position=[x, (y0 + y1) / 2, TOP_RAIL_HEIGHT_M], color=color,
                )

        # Each pod = one trough box (recoloured later by mark_pod_decision), its row of plants
        # (_add_plants), and a small bracket tying it to its pole.
        # troughs (+ a bracket tying each to its pole)
        half = list(TROUGH_HALF_EXTENTS_M)
        bracket_color = (0.3, 0.3, 0.32, 1.0)
        for pod_index, pod in enumerate(self.pods):
            pos = pod["position_m"]
            color = CROP_MARKER_COLOR[pod["crop_type"]]
            vis = p.createVisualShape(p.GEOM_BOX, halfExtents=half, rgbaColor=color)
            body_id = p.createMultiBody(
                baseMass=0, baseCollisionShapeIndex=-1, baseVisualShapeIndex=vis,
                basePosition=[pos["x"], pos["y"], pos["z"]],
            )
            self.pod_marker_ids[pod["pod_id"]] = body_id
            self.obstacles.append((
                f"trough {pod['pod_id']}",
                (pos["x"] - half[0], pos["y"] - half[1], pos["z"] - half[2]),
                (pos["x"] + half[0], pos["y"] + half[1], pos["z"] + half[2]),
            ))

            self._add_plants(pod)
            self._add_pod_label(pod)

            row_y = pod["row"] * ROW_SPACING_M
            bracket_span = pos["y"] - row_y  # signed: + front, - back
            self._add_static_box(
                name=f"bracket {pod['pod_id']}",
                half_extents=[0.025, max(abs(bracket_span) / 2, 0.01), 0.018],
                position=[pos["x"], row_y + bracket_span / 2, pos["z"]],
                color=bracket_color,
            )

    def _identify_pod(self, pod, views):
        """Read the printed tag from the frames the camera just captured (OpenCV, see pod_labels.PodLabelReader).

        Returns the vote over all views plus two facts about WHERE the agent is: `location_label` is the tag that
        should be on the trough the gantry drove to (the gantry navigates by coordinates, as a real one must), and
        `at_expected_location` says whether the tag the camera actually read is that one."""
        frames = [cv2.cvtColor(v["rgba"], cv2.COLOR_RGBA2BGR) for v in views if v.get("rgba") is not None]
        identity = self.label_reader.read_views(frames, keep_evidence=True)
        # Keep ONE compact picture of the reading (frames, located plate, per-character decode) for the application to
        # show, instead of holding every raw frame for every pod.
        evidence = identity.pop("evidence", None)
        if evidence is not None:
            ok, png = cv2.imencode(".png", render_reading_sheet(evidence))
            identity["sheet_png"] = png.tobytes() if ok else None
            identity["evidence_data"] = self._evidence_data(evidence)
        identity["location_label"] = label_for_pod(pod)
        identity["at_expected_location"] = bool(identity["confirmed"] and identity["label"] == identity["location_label"])
        self.pod_identities[pod["pod_id"]] = identity
        return identity

    @staticmethod
    def _evidence_data(evidence):
        """The reading as plain data (JPEG frames, the flattened plate, per-character results) so an interface can draw
        it and play it back stage by stage."""
        views = []
        for v in evidence["views"]:
            ok, jpg = cv2.imencode(".jpg", v["frame"], [cv2.IMWRITE_JPEG_QUALITY, 80])
            views.append({"jpg": jpg.tobytes() if ok else None, "corners": v["corners"], "text": v["text"],
                          "valid": v["valid"], "confidence": v["confidence"], "reason": v["reason"],
                          "shape": [int(evidence_dim) for evidence_dim in v["frame"].shape[:2]]})
        flat_png = None
        if evidence.get("flat") is not None:
            ok, buf = cv2.imencode(".png", evidence["flat"])
            flat_png = buf.tobytes() if ok else None
        return {"views": views, "flat_png": flat_png, "cells": evidence.get("cells", []), "best": evidence.get("best")}

    @staticmethod
    def _identity_record(identity):
        """The JSON-safe summary of a tag read that is stored on the pod's localization record."""
        keys = ("label", "confirmed", "confidence", "views_read", "views_total", "agreeing_views", "conflict",
                "reason", "location_label", "at_expected_location", "per_view")
        return {k: identity.get(k) for k in keys}

    @staticmethod
    def _call_assess(assess, pod, identity):
        """assess(pod, identity=...) when the callback accepts it (the bridge does); plain assess(pod) otherwise, so
        older callbacks keep working."""
        try:
            accepts = "identity" in inspect.signature(assess).parameters
        except (TypeError, ValueError):
            accepts = False
        return assess(pod, identity=identity) if accepts else assess(pod)

    def _label_texture(self, text):
        """PNG file holding the printed tag for `text` (written once, then reused; PyBullet loads textures from disk)."""
        if self._label_dir is None:
            self._label_dir = os.path.join(tempfile.gettempdir(), "farm_pod_tags")
            os.makedirs(self._label_dir, exist_ok=True)
        path = os.path.join(self._label_dir, f"{text}.png")
        if not os.path.exists(path):
            cv2.imwrite(path, render_plate(text))
        return path

    def _add_pod_label(self, pod):
        """Mount the pod's printed number on the aisle-facing wall of its trough (visual-only, like everything else
        in the scene). The text is what the camera agent later reads with OpenCV; nothing else in the simulation
        tells it which pod it is looking at.

        The plate is a flat quad with explicit texture coordinates. Text must read left-to-right for someone standing
        in the aisle looking at the trough: a front-face viewer looks toward -Y, so their right-hand side is -X; a
        back-face viewer looks toward +Y, so their right is +X."""
        text = label_for_pod(pod)
        pos = pod["position_m"]
        out = 1 if pod["side"] == "front" else -1
        y = pos["y"] + out * (TROUGH_HALF_EXTENTS_M[1] + PLATE_STANDOFF_M)
        hw, hh = PLATE_W_M / 2.0, PLATE_H_M / 2.0
        right = -1.0 if out > 0 else 1.0                    # world X direction of the viewer's right-hand side
        corners = [(-hw, -hh), (hw, -hh), (hw, hh), (-hw, hh)]       # local x (along the row), z (up)
        verts = [[cx, 0.0, cz] for cx, cz in corners]
