    def _g_wait(self, seconds):
        """Yield for `seconds` of simulation time (at least one step)."""
        for _ in range(max(1, int(seconds * 240))):
            yield

    def _g_wait_until(self, condition):
        """Yield until `condition()` (a no-argument callable) becomes true. This is
        how the service agent waits for the camera."""
        while not condition():
            yield

    def _settle(self, targets, step_sleep=0.0):
        """Blocking version of _g_settle: run it alone to completion. Used by the
        one-agent-at-a-time moves (driving, stowing, sliding the boxes)."""
        return self._run([self._g_settle(targets)], step_sleep)

    # ---- events -----------------------------------------------------------------------------

    def _emit(self, kind, pod=None, agent=None, **info):
        """Record an event (see the EVENT LOG list in the module docstring) and hand
        it to self.on_event, if set. `pod` is a pod dict or None; `agent` an Agent
        or a string. Extra keyword arguments (plant=, action=, row=, col=) become
        extra fields of the dict."""
        event = {"step": self.sim_steps, "kind": kind,
                 "pod_id": pod["pod_id"] if pod else None,
                 "agent": agent.key if isinstance(agent, Agent) else agent}
        event.update(info)
        self.events.append(event)
        if self.on_event is not None:
            self.on_event(event)

    def _emit_transient(self, kind, pod=None, agent=None, **info):
        """Like _emit, but the event is only handed to on_event and NOT kept in self.events: used for bulky live data
        (camera frames) that would otherwise pile up in the event log for the whole session."""
        if self.on_event is None:
            return
        event = {"step": self.sim_steps, "kind": kind, "pod_id": pod["pod_id"] if pod else None,
                 "agent": agent.key if isinstance(agent, Agent) else agent}
        event.update(info)
        self.on_event(event)

    # ---- rail routing ------------------------------------------------------------------------

    def _plan_rail_route(self, x0, y0, x1, y1):
        """Waypoints (excluding the start) that get the chassis from
        (x0, y0) to (x1, y1) moving along rails only, one axis per leg.
        Both ends must be on a horizontal rail (every station and dock is).
        Changing rails means using one of the two outer vertical rails; the
        cheaper of the two is chosen.

        Examples (rails at y = -0.75, 0, 1.32, 2.64, 3.39; outer rails at x = 0, 1.5):
          same rail            (0.75, 0)  -> (1.5, 0)     [(1.5, 0)]
          dock -> station      (0.75,-0.75) -> (0, 0)     [(0,-0.75), (0, 0)]   left rail, no x leg at the end
          row 0 -> row 1       (1.5, 0) -> (1.5, 1.32)    [(1.5, 1.32)]         already on the right rail
        Every leg changes only x OR only y (asserted by _drive_to)."""
        tol = ON_RAIL_TOLERANCE_M
        if not any(abs(y1 - ry) < tol for ry in HORIZONTAL_RAIL_YS):
            raise ValueError(f"goal y={y1:.3f} is not on a horizontal rail")
        if abs(y1 - y0) < tol:
            return [(x1, y1)]

        start_on_horizontal = any(abs(y0 - ry) < tol for ry in HORIZONTAL_RAIL_YS)
        best = None
        for xv in VERTICAL_RAIL_XS:
            if abs(x0 - xv) > tol and not start_on_horizontal:
                continue
            route = []
            length = 0.0
            if abs(x0 - xv) > tol:
                route.append((xv, y0))
                length += abs(x0 - xv)
            route.append((xv, y1))
            length += abs(y1 - y0)
            if abs(x1 - xv) > tol:
                route.append((x1, y1))
                length += abs(x1 - xv)
            if best is None or length < best[0]:
                best = (length, route)
        if best is None:
            raise ValueError(f"chassis at ({x0:.3f}, {y0:.3f}) is not on a rail")
        return best[1]

    def _drive_to(self, x, y, step_sleep=0.0):
        """Drive the chassis to (x, y) along the rails. One axis at a time --
        a diagonal leg would mean cutting across open air between rails --
        and only with everything stowed (asserted: the machine must never move
        with a hoist out, a head off-centre or an applicator extended)."""
        assert self.all_stowed(), "the machine must never move with a hoist deployed"
        x0, y0 = self.chassis_xy()
        steps = 0
        for wx, wy in self._plan_rail_route(x0, y0, x, y):
            cx, cy = self.chassis_xy()
            moves_x = abs(wx - cx) > ON_RAIL_TOLERANCE_M
            moves_y = abs(wy - cy) > ON_RAIL_TOLERANCE_M
            assert not (moves_x and moves_y), "rail route produced a diagonal leg"
            if moves_y:
                assert self.boxes_retracted(), "changing horizontal pole needs the drive boxes slid in"
            if moves_x:
                steps += self._settle({self.carriage_joint: wx}, step_sleep)
            elif moves_y:
                steps += self._settle({self.row_joint: wy}, step_sleep)
            # GUI only: a red line along the leg just driven (cheap: one debug line per leg)
            if self.show_trail:
                z = RAIL_TOP_Z + 0.004
                p.addUserDebugLine([cx, cy, z], [wx, wy, z],
                                   lineColorRGB=[0.9, 0.1, 0.1], lineWidth=3)
        return steps

    def _stow_all(self, step_sleep=0.0):
        """Centre every head on its traverse, THEN pull every hoist up (compact).
        Order matters: heads are centred first so the traverse is folded behind the
        rod before the hoist rises past anything. Skips the centring move if all
        heads are already home."""
        steps = 0
        if any(abs(self.stage_offset(a)) >= STAGE_HOME_TOL_M for a in self.agents):
            steps += self._settle({j: 0.0 for a in self.agents for j in a.stage_joints}, step_sleep)
        steps += self._settle({a.joint: 0.0 for a in self.agents}, step_sleep)
        return steps

    def disengage_boxes(self, step_sleep=0.0):
        """Slide the two drive boxes in toward each other (compact travel
        configuration). Only with every hoist stowed and the machine still.
        Does nothing if they are already in."""
        if self.boxes_retracted():
            return 0
        assert self.all_stowed(), "drive boxes must only slide with every hoist stowed"
        self._emit("boxes_disengage")
        return self._settle({j: BOX_STROKE_M for j in self.box_joint.values()}, step_sleep)

    def engage_boxes(self, step_sleep=0.0):
        """Slide the two drive boxes back out to their operating position
        0.445m either side of the beam. Does nothing if they are already out."""
        if self.boxes_engaged():
            return 0
        assert self.all_stowed(), "drive boxes must only slide with every hoist stowed"
        self._emit("boxes_engage")
        return self._settle({j: 0.0 for j in self.box_joint.values()}, step_sleep)

    # ---- the two agents' jobs -----------------------------------------------------------------
    #
    # _g_camera and _g_service are the two halves of the pipeline. They never call each other;
    # they share ONE small dict per station, `shared`:
    #     shared["assessed"][pod_id]  the dict returned by assess(pod) (set by the camera)
    #     shared["camera_left"][side] how many pods the camera on that side has FINISHED and left
    # The service agent for pod i blocks on  camera_left[side] > i  -- that single line is the
    # "camera first, then service" rule. Everything else is each agent's own motion.

    def _plant_order(self, n, direction):
        """Plant indices 0..n-1 in order (direction > 0) or reversed. Heads alternate
        direction pod to pod so they sweep back and forth instead of running back."""
        return range(n) if direction > 0 else range(n - 1, -1, -1)

    def _g_camera(self, side, pods, assess, shared):
        """Camera agent for one side. At each pod its head slides along the pod
        past every plant in turn, pausing to image each one; once all the plants
        are imaged it assesses the pod, holds, then moves on to the next pod
        (sweeping the other way, so it never has to run back). After the last pod
        it centres its head and stows."""
        # (1) descend to the first (top) pod. Nothing else is deployed yet.
        cam = self.agent(side, "camera")
        if sim_options.OPTIONS["stereo_rig"] and not self._rig_checked:
            # Both camera agents share one rig design. The robot only LOADS the saved calibration (made from the
            # application's Calibration tab) -- it never runs a calibration itself, which could stall the step loop.
            self._rig_checked = True
            from .multiview_localization import IMAGE_WIDTH as _W, IMAGE_HEIGHT as _H
