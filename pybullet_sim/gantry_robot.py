    # =========================================================================
    # STATE READERS  (small, cheap, side-effect free; all values in metres)
    # =========================================================================
    # Everything the rest of the code (and verify_motion.py) needs to know about the machine's
    # pose is derived from JOINT VALUES with the formulas below; agent_head_position_from_link()
    # reads the same thing from the simulator's link frames so the checker can prove the two agree.

    def _joint(self, joint):
        """Position of joint index `joint` (a prismatic joint: metres)."""
        return p.getJointState(self.robot_id, joint)[0]

    def chassis_xy(self):
        """(x, y) of the machine's centre in world coordinates. Because the URDF
        base sits at world (0, 0, BASE_Z), these are just the carriage_joint and
        row_joint values."""
        return self._joint(self.carriage_joint), self._joint(self.row_joint)

    def hoist_extension(self, agent):
        """How far the agent's hoist has moved DOWN from the drive box (0 = stowed)."""
        return self._joint(agent.joint)

    def applicator_extension(self, agent):
        """How far the agent's contact applicator is slid out (0 for camera agents)."""
        return 0.0 if agent.applicator_joint is None else self._joint(agent.applicator_joint)

    def box_inward(self, side):
        """How far the drive box on `side` has slid in toward the beam
        (0 = engaged / operating position, BOX_STROKE_M = fully disengaged)."""
        return self._joint(self.box_joint[side])

    def boxes_engaged(self):
        """True when BOTH drive boxes are out at their operating position."""
        return all(self.box_inward(sd) < BOX_ENGAGED_M for sd in ("front", "back"))

    def boxes_retracted(self):
        """True when BOTH drive boxes are slid fully in (the travel/dock configuration)."""
        return all(self.box_inward(sd) > BOX_RETRACTED_MIN_M for sd in ("front", "back"))

    def stage_offset(self, agent):
        """How far the agent's traverse carriage is from the middle of its
        guide rail (0 = home / centred)."""
        return sum(self._joint(j) for j in agent.stage_joints)

    def stage_speed(self, agent):
        """How fast the agent's head is sliding along the pod (m/s, signed)."""
        return sum(p.getJointState(self.robot_id, j)[1] for j in agent.stage_joints)

    def stage_cmd(self, agent, offset):
        """Joint targets that put the agent's head `offset` metres from its rod
        along X: the two telescoping stages share the travel equally."""
        return {j: offset / 2 for j in agent.stage_joints}

    def all_stowed(self):
        """Every hoist up, every applicator pulled in and every head back at
        the middle of its rail -- the only (compact) state the machine is
        allowed to slide its boxes or change rails in."""
        return all(self._joint(a.joint) < STOWED_TOLERANCE_M
                   and self.applicator_extension(a) < APPLICATOR_RETRACTED_M
                   and abs(self.stage_offset(a)) < STAGE_HOME_TOL_M
                   for a in self.agents)

    def rod_y(self, agent):
        """Offset from the chassis centre, along Y, at which the agent's rod hangs:
        sign * (box centre distance - how far the box has slid in + the agent's bay offset).
        E.g. engaged, front camera: +1 * (0.445 - 0 + 0.06) = +0.505."""
        return agent.sign * (BOX_REACH_M - self.box_inward(agent.side) + agent.bay)

    def agent_head_position(self, agent):
        """(x, y, z) of the agent's tool-head centre in WORLD coordinates, computed
        from joint values: x = machine x + the rod's x offset + the traverse offset,
        y = machine y + rod_y(), z = hoist origin - hoist extension - HEAD_DROP_M."""
        cx, cy = self.chassis_xy()
        return (cx + agent.dx + self.stage_offset(agent), cy + self.rod_y(agent),
                HOIST_ORIGIN_Z - self._joint(agent.joint) - HEAD_DROP_M)

    def agent_head_position_from_link(self, agent):
        """Same thing read from the SIMULATOR's link frame (i.e. from the URDF),
        used by verify_motion.py to prove the URDF and the constants in this file
        agree. PyBullet numbers a link with the index of the joint that leads to
        it, so stage_joints[1] is the carriage link (child of stage2)."""
        link = agent.stage_joints[1]    # the carriage's link (child of stage2); index == joint index
        x, y, z = p.getLinkState(self.robot_id, link)[4]
        return (x, y, z - (HEAD_DROP_M - RAIL_DROP_M))

    def applicator_tip(self, agent):
        """World position of the front face of a service agent's contact pad
        (retracted, or wherever it is slid out to)."""
        x, y, z = self.agent_head_position(agent)
        reach = APPLICATOR_RETRACTED_TIP_M + self.applicator_extension(agent)
        return (x, y + agent.toward * reach, z)

    def trough_face_y(self, pod):
        """World y of the trough face the agents on this pod's side look at."""
        sign = 1 if pod["side"] == "front" else -1
        return pod["row"] * ROW_SPACING_M + sign * FACE_OFFSET_M

    def plant_front_y(self, pod):
        """World y of the front of the plants on this pod (what a pad touches)."""
        return pod["plants"][0]["y_front"]

    def stage_target_for_plant(self, agent, pod, k):
        """Traverse offset (metres from the rod, signed along +x) that puts the
        agent's head in front of plant k of `pod`: the plant's x minus the rod's
        x (pole x + agent.dx). Pass the result to stage_cmd()."""
        return pod["plants"][k]["x"] - (pod["position_m"]["x"] + agent.dx)

    def _park_initial_pose(self):
        """Start parked on the top dock bar (rail 1), all four hoists stowed and
        the drive boxes slid in (disengaged, as on every dock) -- so the first
        thing the machine does is work, not a diagonal drift from the world
        origin to the dock."""
        initial = {self.carriage_joint: DOCK_PARK_X, self.row_joint: TOP_DOCK_Y}
        initial.update({j: BOX_STROKE_M for j in self.box_joint.values()})
        initial.update({a.joint: 0.0 for a in self.agents})
        initial.update({j: 0.0 for a in self.agents for j in a.stage_joints})
        initial.update({a.applicator_joint: 0.0 for a in self.agents if a.applicator_joint is not None})
        for joint, value in initial.items():
            p.resetJointState(self.robot_id, joint, value)
            force, vel = self._drive[joint]
            p.setJointMotorControl2(
                self.robot_id, joint, p.POSITION_CONTROL,
                targetPosition=value, force=force, maxVelocity=vel,
            )
        # one step so link poses (getLinkState) reflect the reset joint states
        p.stepSimulation()

